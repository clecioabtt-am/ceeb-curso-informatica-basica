CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS tutor_usage (key TEXT PRIMARY KEY, count INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS quiz_records (learner TEXT NOT NULL, module INTEGER NOT NULL, answers TEXT NOT NULL, questions TEXT NOT NULL, score INTEGER NOT NULL, submitted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(learner,module));
